export function normalizePlace(value: string | null | undefined) {
  return value
    ?.trim()
    .toLowerCase()
    .replace(/\s+/g, " ")
    .replace("обл.", "область");
}

export function resolveLocation(input: {
  region?: string | null;
  locality?: string | null;
}) {
  const city = normalizePlace(input.locality);
  if (city && city in cityCoordinates) {
    return cityCoordinates[city as keyof typeof cityCoordinates];
  }

  const region = normalizePlace(input.region);
  if (region && region in regionCoordinates) {
    return regionCoordinates[region as keyof typeof regionCoordinates];
  }

  return null;
}
